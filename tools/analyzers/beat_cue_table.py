"""Beat-cue word table: P(a dramatic beat starts at this unit | its words, the end of the previous unit, unit kinds).

Trained on Sonnet beat2 labels; used as a feature (beatCue) by the beat2 tree model, which trains on Opus labels.
Tokens are built exactly like rules.js cueTokens (pre-tokenized, unigrams + adjacent bigrams like scoreTokens).
  python beat_cue_table.py [--vocab 3000]     # writes src/analyzers/beatcue.js
"""
import argparse, base64, gzip, json, re
import numpy as np
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.linear_model import LogisticRegression
import beats2 as B
import label as L

TOK = re.compile(r"__\w+|[a-z]+(?:'[a-z]+)?|[!?:]")


def cue_tokens(units, k):
    u = units[k]; p = units[k - 1] if k > 0 else None
    cur = TOK.findall(u["text"].lower())
    prev = TOK.findall(p["text"].lower())[-4:] if p else []
    return ["__k" + u["kind"][0], "__pk" + (p["kind"][0] if p else "n")] + cur + ["__p" + w for w in prev]


def grams(toks):
    return toks + [a + " " + b for a, b in zip(toks, toks[1:])]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--vocab", type=int, default=3000)
    a = ap.parse_args()
    lab = {}
    for t in ("sonnet", "csonnet"):
        lab.update(B.load(t))
    gold = B.consensus(["opusA", "opusB", "opusC"], need=2)
    X, y = [], []
    for s, bs in lab.items():
        if s in gold:
            continue
        try:
            us = [u for u in L.load_units(s)["units"] if u["kind"] in ("action", "dialogue")]
        except FileNotFoundError:
            continue
        starts = {b["start"] for b in bs}
        for k in range(1, len(us)):
            X.append(grams(cue_tokens(us, k))); y.append(int(us[k]["u"] in starts))
    y = np.array(y)
    vec = CountVectorizer(analyzer=lambda d: d, max_features=a.vocab, binary=True, min_df=3)
    clf = LogisticRegression(C=0.3, max_iter=3000, class_weight="balanced").fit(vec.fit_transform(X), y)
    Xg, yg = [], []
    for s, g in gold.items():
        us = [u for u in L.load_units(s)["units"] if u["kind"] in ("action", "dialogue")]
        for k in range(1, len(us)):
            Xg.append(grams(cue_tokens(us, k))); yg.append(int(us[k]["u"] in set(g["starts"])))
    from sklearn.metrics import roc_auc_score
    print(f"train rows {len(y)}; gold AUC {roc_auc_score(yg, clf.predict_proba(vec.transform(Xg))[:, 1]):.3f}")
    W = np.vstack([-clf.coef_[0], clf.coef_[0]]) / 2
    b = [-clf.intercept_[0] / 2, clf.intercept_[0] / 2]
    q = np.round(W / np.abs(W).max() * 127).astype(np.int8)
    js = ("// Generated by tools/analyzers/beat_cue_table.py. Learned beat-start cue weights (int8). Do not edit.\n"
          f"export default {{classes:[\"no\",\"start\"],scale:{float(np.abs(W).max() / 127)},bias:{json.dumps([round(x, 4) for x in b])},"
          f"vocab:{json.dumps(vec.get_feature_names_out().tolist(), separators=(',', ':'))},w:\"{base64.b64encode(q.T.astype(np.int8).tobytes()).decode()}\"}};\n")
    (L.ROOT / "src/analyzers/beatcue.js").write_text(js)
    print(f"beatcue.js {len(js) / 1024:.0f} KB, {len(gzip.compress(js.encode())) / 1024:.0f} KB gz")


if __name__ == "__main__":
    main()
