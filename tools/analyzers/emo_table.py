"""Learned word table for emotion: logistic regression over words / word pairs, exported as a small lookup table.

  python emo_table.py --sweep            # accuracy vs vocabulary size on the gold sets
  python emo_table.py --vocab 3000       # writes src/analyzers/emotable.js
"""
import argparse, gzip, json, re
import numpy as np
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.linear_model import LogisticRegression
import label as L

EMOTIONS = ["neutral", "joy", "sadness", "anger", "fear", "surprise", "disgust", "affection"]
TOKEN = r"[a-z]+(?:'[a-z]+)?|[!?]"


def unit_text(u):
    return (u["text"] + " " + " ".join(u.get("paren") or [])).lower()


def train_rows():
    X, y = [], []
    cache = {}
    for l in (L.DATA / "train_lines.jsonl").open():
        d = json.loads(l)
        s = d["scene_id"]
        if s not in cache:
            try:
                cache = {s: {u["u"]: u for u in L.load_units(s)["units"]}}
            except FileNotFoundError:
                cache = {s: {}}
        u = cache[s].get(d["line"])
        if not u:
            continue
        e = d.get("emotion")
        X.append(("D " if u["kind"] == "dialogue" else "A ") + unit_text(u)); y.append(EMOTIONS.index(e[0]) if e and e[0] in EMOTIONS else 0)
    return X, np.array(y)


def gold_rows():
    out = {"syn": ([], []), "pd": ([], [])}
    for f in ("gold.jsonl", "gold_pd.jsonl"):
        for l in (L.DATA / f).open():
            g = json.loads(l)
            units = {u["u"]: u for u in L.load_units(g["scene_id"])["units"]}
            k = "pd" if g["scene_id"].startswith("pd_") else "syn"
            for n, v in g["units"].items():
                u = units.get(int(n))
                if not u or u["kind"] not in ("action", "dialogue"):
                    continue
                e = v.get("emo") or ["neutral", 0]
                out[k][0].append(("D " if u["kind"] == "dialogue" else "A ") + unit_text(u)); out[k][1].append(EMOTIONS.index(e[0]) if e[0] in EMOTIONS else 0)
    return {k: (a, np.array(b)) for k, (a, b) in out.items()}


def fit(X, y, vocab, C=1.0):
    vec = CountVectorizer(token_pattern=TOKEN, ngram_range=(1, 2), max_features=vocab, binary=True, min_df=3)
    Xv = vec.fit_transform(X)
    clf = LogisticRegression(C=C, max_iter=2000, class_weight=None).fit(Xv, y)
    return vec, clf


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--sweep", action="store_true"); ap.add_argument("--vocab", type=int, default=3000)
    ap.add_argument("--C", type=float, default=1.0)
    a = ap.parse_args()
    X, y = train_rows()
    G = gold_rows()
    print(f"train {len(y)} lines; gold syn {len(G['syn'][1])}, pd {len(G['pd'][1])}")
    for vocab in ([500, 1000, 2000, 3000, 5000, 8000] if a.sweep else [a.vocab]):
        vec, clf = fit(X, y, vocab, a.C)
        acc = {k: float(np.mean(clf.predict(vec.transform(gx)) == gy)) for k, (gx, gy) in G.items()}
        W = clf.coef_  # classes x vocab
        q = np.round(W / np.abs(W).max() * 127).astype(np.int8)
        vocab_list = vec.get_feature_names_out().tolist()
        payload = json.dumps({"v": vocab_list, "w": q.T.flatten().tolist(), "s": float(np.abs(W).max() / 127), "b": clf.intercept_.tolist()}, separators=(",", ":"))
        print(f"vocab {vocab:5d}: syn {acc['syn']:.1%}  pd {acc['pd']:.1%}  size {len(payload)/1024:.0f} KB raw, {len(gzip.compress(payload.encode()))/1024:.0f} KB gz")
    if not a.sweep:
        cls = [EMOTIONS[c] for c in clf.classes_]
        js = L.ROOT / "src/analyzers/emotable.js"
        js.write_text("// Generated by tools/analyzers/emo_table.py. Learned word -> emotion weights (int8). Do not edit.\n"
                      f"export default {{classes:{json.dumps(cls)},scale:{float(np.abs(W).max() / 127)},bias:{json.dumps([round(b, 4) for b in clf.intercept_.tolist()])},"
                      f"vocab:{json.dumps(vocab_list, separators=(',', ':'))},w:\"{__import__('base64').b64encode(q.T.astype(np.int8).tobytes()).decode()}\"}};\n")
        print("wrote", js, f"{js.stat().st_size / 1024:.0f} KB")


if __name__ == "__main__":
    main()
