"""Learned word table for line kind (setting / event / extra / camera / abstract) of action lines without a character.

Trains on Haiku kind labels (+ the Opus gold labels with --gold-weight; honest accuracy then comes from kind_cv.py),
tests on Opus gold kind labels. Rule signals from rules.js enter as extra tokens.
  python kind_table.py [--vocab 2000]      # writes src/analyzers/kindtable.js
"""
import argparse, base64, glob, gzip, json, subprocess
import numpy as np
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.linear_model import LogisticRegression
import dataset as DS
import label as L

KINDS = ["setting", "event", "extra", "camera", "abstract"]
TOKEN = r"[a-z]+(?:'[a-z]+)?|[!?:]|__\w+"


def rows(tag):
    reqs = []
    for f in sorted(glob.glob(str(L.LAB / f"kinds_{tag}/group_*.json"))):
        try:
            data = json.load(open(f))
        except json.JSONDecodeError:
            continue
        for s, v in data.items():
            try:
                d = L.load_units(s)
            except FileNotFoundError:
                continue
            kinds = {u["u"]: u["kind"] for u in d["units"]}
            for u, k in v.items():
                if kinds.get(int(u)) == "action" and isinstance(k, str) and k in KINDS:
                    reqs.append({"source": d["source"], "index": DS.scene_index(s, d["source"]), "u": int(u), "kind": k})
    out = subprocess.run(["node", "kinds_eval.mjs", "--signals"], input="".join(json.dumps(r) + "\n" for r in reqs),
                         capture_output=True, text=True, check=True).stdout
    R = [json.loads(l) for l in out.splitlines()]
    return [r["sig"] for r in R], np.array([KINDS.index(r["kind"]) for r in R]), [r["pred"] for r in R]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--vocab", type=int, default=2000); ap.add_argument("--C", type=float, default=0.5)
    ap.add_argument("--sweep", action="store_true")
    ap.add_argument("--gold-weight", type=float, default=0, help="also train on the Opus gold kind labels, with this weight (then the gold accuracy printed is in-sample; see kind_cv.py for the honest number)")
    a = ap.parse_args()
    X, y, _ = rows("haiku")
    Xg, yg, rule = rows("opus")
    print(f"train {len(y)}  gold {len(yg)}  rules-only gold acc {np.mean([KINDS.index(p) == t if p in KINDS else False for p, t in zip(rule, yg)]):.1%}")
    for vocab in ([500, 1000, 2000, 4000] if a.sweep else [a.vocab]):
        vec = CountVectorizer(token_pattern=TOKEN, ngram_range=(1, 2), max_features=vocab, binary=True, min_df=2, lowercase=False)
        Xtr, ytr, sw = X, y, None
        if a.gold_weight:
            Xtr = list(X) + list(Xg); ytr = np.concatenate([y, yg]); sw = np.concatenate([np.ones(len(y)), np.full(len(yg), a.gold_weight)])
        clf = LogisticRegression(C=a.C, max_iter=3000).fit(vec.fit_transform(Xtr), ytr, sample_weight=sw)
        acc = float(np.mean(clf.predict(vec.transform(Xg)) == yg))
        W = clf.coef_
        q = np.round(W / np.abs(W).max() * 127).astype(np.int8)
        vocab_list = vec.get_feature_names_out().tolist()
        b64 = base64.b64encode(q.T.astype(np.int8).tobytes()).decode()
        js = ("// Generated by tools/analyzers/kind_table.py. Learned word -> line-kind weights (int8). Do not edit.\n"
              f"export default {{classes:{json.dumps([KINDS[c] for c in clf.classes_])},scale:{float(np.abs(W).max() / 127)},"
              f"bias:{json.dumps([round(b, 4) for b in clf.intercept_.tolist()])},vocab:{json.dumps(vocab_list, separators=(',', ':'))},w:\"{b64}\"}};\n")
        print(f"vocab {vocab}: gold acc {acc:.1%}{' (in-sample: gold in training)' if a.gold_weight else ''}  {len(js) / 1024:.0f} KB raw, {len(gzip.compress(js.encode())) / 1024:.0f} KB gz")
        cm = np.zeros((5, 5), int)
        for t, p in zip(yg, clf.predict(vec.transform(Xg))):
            cm[t, p] += 1
        print("  confusion (rows gold):", KINDS); print(cm)
    if not a.sweep:
        (L.ROOT / "src/analyzers/kindtable.js").write_text(js)


if __name__ == "__main__":
    main()
