"""Line kind: word table (kindtable.js) + context stack (models.kind in the bundle). Trains on Opus + Haiku kind labels,
tests on Opus gold kinds.  python kind_train.py [--tags opusKT,haiku] [--vocab 2000]"""
import argparse, base64, gzip, json, os, subprocess, sys
import numpy as np, lightgbm as lgb
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.linear_model import LogisticRegression
from sklearn.model_selection import GroupKFold
import dataset as DS, label as L, kind_table as K
from train import dump

sys.path.insert(0, os.path.dirname(__file__))


def rows(tag):
    import glob
    reqs = []
    for f in sorted(glob.glob(str(L.LAB / f"kinds_{tag}/group_*.json"))):
        try:
            data = json.load(open(f))
        except json.JSONDecodeError:
            continue
        for s, v in data.items():
            try:
                d = L.load_units(s)
            except FileNotFoundError:
                continue
            kinds = {u["u"]: u["kind"] for u in d["units"]}
            for u, k in v.items():
                if kinds.get(int(u)) == "action" and isinstance(k, str) and k in K.KINDS:
                    reqs.append({"sid": s, "source": d["source"], "index": DS.scene_index(s, d["source"]), "u": int(u), "kind": k})
    out = subprocess.run(["node", "kinds_eval.mjs", "--signals"], input="".join(json.dumps(r) + "\n" for r in reqs),
                         capture_output=True, text=True, check=True).stdout
    return [json.loads(l) for l in out.splitlines()]


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--tags", default="opusKT,haiku"); ap.add_argument("--vocab", type=int, default=2000)
    a = ap.parse_args()
    T = sum((rows(t) for t in a.tags.split(",")), [])
    G = rows("opus")
    gold_s = {r["sid"] for r in G}
    T = [r for r in T if r["sid"] not in gold_s]
    y = np.array([K.KINDS.index(r["kind"]) for r in T]); yg = np.array([K.KINDS.index(r["kind"]) for r in G])
    sid = np.array([r["sid"] for r in T])
    vec = CountVectorizer(token_pattern=K.TOKEN, ngram_range=(1, 2), max_features=a.vocab, binary=True, min_df=2, lowercase=False)
    X = vec.fit_transform([r["sig"] for r in T]); Xg = vec.transform([r["sig"] for r in G])
    oof = np.zeros((len(y), 5))
    for tr, te in GroupKFold(5).split(X, y, sid):
        m = LogisticRegression(C=0.5, max_iter=3000).fit(X[tr], y[tr])
        oof[np.ix_(te, m.classes_)] = m.predict_proba(X[te])
    lr = LogisticRegression(C=0.5, max_iter=3000).fit(X, y)
    pg = np.zeros((len(yg), 5)); pg[:, lr.classes_] = lr.predict_proba(Xg)
    Z = np.hstack([oof, np.array([r["ctxf"] for r in T])]); Zg = np.hstack([pg, np.array([r["ctxf"] for r in G])])
    gbm = lgb.LGBMClassifier(n_estimators=120, learning_rate=0.06, num_leaves=15, verbose=-1).fit(Z, y)
    print(f"train lines {len(y)}; gold: table {np.mean(pg.argmax(1) == yg):.1%}  stack {np.mean(gbm.predict(Zg) == yg):.1%}")
    W = lr.coef_; q = np.round(W / np.abs(W).max() * 127).astype(np.int8)
    js = ("// Generated by tools/analyzers/kind_train.py. Learned word -> line-kind weights (int8). Do not edit.\n"
          f"export default {{classes:{json.dumps([K.KINDS[c] for c in lr.classes_])},scale:{float(np.abs(W).max() / 127)},"
          f"bias:{json.dumps([round(b, 4) for b in lr.intercept_.tolist()])},vocab:{json.dumps(vec.get_feature_names_out().tolist(), separators=(',', ':'))},"
          f"w:\"{base64.b64encode(q.T.astype(np.int8).tobytes()).decode()}\"}};\n")
    (L.ROOT / "src/analyzers/kindtable.js").write_text(js)
    path = L.ROOT / "public/models/analyzers.json"
    b = json.loads(path.read_text())
    b["models"]["kind"] = dump(gbm, "multiclass")
    b["meta"]["kind"] = {"classes": [K.KINDS[int(c)] for c in gbm.classes_], "table_order": K.KINDS}
    path.write_text(json.dumps(b, separators=(",", ":")))


if __name__ == "__main__":
    main()
