"""Beat mood: learned word table over the beat's text + signal tokens -> 16 moods (6 families).

Trains on Sonnet beat2 labels (each beat's text and mood), tests per content unit on Opus majority gold, using the gold
beats (mood given perfect beats) — the app's real accuracy also depends on beat boundaries.
  python mood_table.py [--vocab 3000]     # writes src/analyzers/moodtable.js
"""
import argparse, base64, collections, gzip, json, re
import numpy as np
from sklearn.feature_extraction.text import CountVectorizer
from sklearn.linear_model import LogisticRegression
import beats2 as B
import label as L

MOODS = L.MOODS
TOKEN = r"__\w+|[a-z]+(?:'[a-z]+)?|[!?:]"
EXPL = {k: re.compile(v, re.I) for k, v in {
    "anger": r"\b(angry|furious|rage|hate|yell|shout|scream|slam|fuck|damn)\w*", "fear": r"\b(afraid|scared|terrif|panic|trembl|fear)\w*",
    "sad": r"\b(cry|cries|tears|sob|grief|mourn|funeral|sad|miss)\w*", "joy": r"\b(laugh|grin|smile|cheer|celebrat|happy)\w*",
    "tender": r"\b(hug|kiss|hold|gentle|soft|love|darling)\w*", "threat": r"\b(gun|knife|blood|kill|dead|shoot|bomb|threat)\w*"}.items()}


def beat_text(units, lo, hi):
    """Text of content units lo <= u < hi with kind prefixes and signal tokens (shared with JS moodSignals)."""
    us = [u for u in units if u["kind"] in ("action", "dialogue") and lo <= u["u"] < hi]
    txt = " ".join(u["text"] for u in us)
    sig = []
    q = txt.count("?"); e = txt.count("!")
    sig.append("__q0" if q == 0 else "__q1" if q <= 2 else "__q3")
    sig.append("__e0" if e == 0 else "__e1" if e <= 2 else "__e3")
    d = sum(u["kind"] == "dialogue" for u in us) / max(1, len(us))
    sig.append("__dlg0" if d < 0.2 else "__dlg1" if d < 0.6 else "__dlg2")
    for k, r in EXPL.items():
        n = len(r.findall(txt))
        if n: sig.append(f"__{k}{min(n, 3)}")
    sig.append("__len" + ("s" if len(us) <= 4 else "m" if len(us) <= 12 else "l"))
    return " ".join(sig) + " " + txt.lower()


def rows(labels):
    X, y = [], []
    for s, beats in labels.items():
        try:
            units = L.load_units(s)["units"]
        except FileNotFoundError:
            continue
        for k, b in enumerate(beats):
            hi = beats[k + 1]["start"] if k + 1 < len(beats) else 10**9
            if b.get("mood") in MOODS:
                X.append(beat_text(units, b["start"], hi)); y.append(MOODS.index(b["mood"]))
    return X, np.array(y)


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--vocab", type=int, default=3000); ap.add_argument("--C", type=float, default=0.5)
    ap.add_argument("--sweep", action="store_true")
    a = ap.parse_args()
    train = {}
    for tag in ("sonnet", "csonnet"):
        train.update(B.load(tag))
    gold = B.consensus([t for t in ("opusA", "opusB", "opusC") if B.load(t)], need=2)
    train = {k: v for k, v in train.items() if k not in gold}
    X, y = rows(train)
    print(f"train beats {len(y)}; gold scenes {len(gold)}")
    fam_idx = [B.FAMILIES.index(B.FAM[m]) for m in MOODS]
    for vocab in ([1000, 2000, 3000, 5000] if a.sweep else [a.vocab]):
        vec = CountVectorizer(token_pattern=TOKEN, ngram_range=(1, 2), max_features=vocab, binary=True, min_df=2, lowercase=False)
        clf = LogisticRegression(C=a.C, max_iter=3000).fit(vec.fit_transform(X), y)
        c = collections.Counter()
        for s, g in gold.items():
            units = L.load_units(s)["units"]
            st = g["starts"]
            for k, lo in enumerate(st):
                hi = st[k + 1] if k + 1 < len(st) else 10**9
                p = clf.predict_proba(vec.transform([beat_text(units, lo, hi)]))[0]
                full = np.zeros(len(MOODS)); full[clf.classes_] = p
                fam = np.zeros(len(B.FAMILIES))
                for m, v in enumerate(full): fam[fam_idx[m]] += v
                pm, pf = MOODS[int(full.argmax())], B.FAMILIES[int(fam.argmax())]
                for u in [u["u"] for u in units if u["kind"] in ("action", "dialogue") and lo <= u["u"] < hi]:
                    c["n"] += 1; c["fine"] += pm == g["mood"].get(u); c["fam"] += pf == g["fam"].get(u)
        W = clf.coef_
        q = np.round(W / np.abs(W).max() * 127).astype(np.int8)
        js = ("// Generated by tools/analyzers/mood_table.py. Learned beat-text -> mood weights (int8). Do not edit.\n"
              f"export default {{classes:{json.dumps([MOODS[k] for k in clf.classes_])},scale:{float(np.abs(W).max() / 127)},"
              f"bias:{json.dumps([round(b, 4) for b in clf.intercept_.tolist()])},vocab:{json.dumps(vec.get_feature_names_out().tolist(), separators=(',', ':'))},"
              f"w:\"{base64.b64encode(q.T.astype(np.int8).tobytes()).decode()}\"}};\n")
        print(f"vocab {vocab}: per-unit mood {c['fine'] / c['n']:.1%}  family {c['fam'] / c['n']:.1%}  ({len(gzip.compress(js.encode())) / 1024:.0f} KB gz)")
    if not a.sweep:
        (L.ROOT / "src/analyzers/moodtable.js").write_text(js)


if __name__ == "__main__":
    main()
