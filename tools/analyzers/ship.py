"""Write the shipped bundle src/analyzers/weights.js from public/models/analyzers.json, minus models the app does not use."""
import gzip, json
import label as L

UNUSED = ("actor",)  # who is rule-based


def main():
    b = json.loads((L.ROOT / "public/models/analyzers.json").read_text())
    for k in UNUSED:
        b["models"].pop(k, None)
    js = "// Generated by tools/analyzers/ship.py from public/models/analyzers.json. Do not edit.\nexport default " + json.dumps(b, separators=(",", ":")) + ";\n"
    (L.ROOT / "src/analyzers/weights.js").write_text(js)
    print(f"weights.js {len(js) / 1024:.0f} KB raw, {len(gzip.compress(js.encode())) / 1024:.0f} KB gz")


if __name__ == "__main__":
    main()
