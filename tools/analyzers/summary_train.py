"""Key-line scorer for extractive beat summaries (summarize.js), trained on Sonnet beat2 summaries.

Target per beat: the unit whose words overlap the labeled summary most. Scored on Opus gold beats by
key-line accuracy and ROUGE-1 F of the composed summary vs the Opus summary (baselines: first line, longest line).
  python summary_train.py
"""
import collections, json, re, subprocess
import lightgbm as lgb
import numpy as np
import beats2 as B
import dataset as DS
import label as L
from train import dump

STOP = set("the a an and of to in on at with for his her their its is are was be he she they it as by from that this into".split())
toks = lambda t: [w for w in re.findall(r"[a-z]{3,}", t.lower()) if w not in STOP]


def rouge1(a, b):
    A, Bc = collections.Counter(toks(a)), collections.Counter(toks(b))
    ov = sum((A & Bc).values())
    if not ov:
        return 0.0
    p, r = ov / max(1, sum(A.values())), ov / max(1, sum(Bc.values()))
    return 2 * p * r / (p + r)


def feats(labels):
    reqs = []
    for s, bs in labels.items():
        d = L.load_units(s)
        reqs.append({"scene_id": s, "source": d["source"], "index": DS.scene_index(s, d["source"]),
                     "beats": [{"start": b["start"], "summary": b.get("summary", "")} for b in bs]})
    out = subprocess.run(["node", "summary_features.mjs"], input="".join(json.dumps(r) + "\n" for r in reqs),
                         capture_output=True, text=True, check=True).stdout
    return {d["scene_id"]: d for d in map(json.loads, out.splitlines())}


def targets(labels, F):
    rows = []
    for s, bs in labels.items():
        f = F.get(s)
        if not f:
            continue
        units = {u["u"]: u for u in L.load_units(s)["units"]}
        for b, fb in zip(bs, f["beats"]):
            if not fb["units"]:
                continue
            ov = [rouge1(units[i]["text"] + " " + (units[i].get("name") or ""), b.get("summary", "")) if i in units else 0.0 for i in fb["units"]]
            rows.append((s, b, fb, int(np.argmax(ov)), ov))
    return rows


def main():
    train = {}
    for tag in ("sonnet", "csonnet", "opusT"):  # later tags win: Opus summaries where available
        train.update(B.load(tag))
    gold = B.load("opusA")
    train = {k: v for k, v in train.items() if k not in gold}
    Ft, Fg = feats(train), feats(gold)
    R = targets(train, Ft)
    X = np.array([x for _, _, fb, _, _ in R for x in fb["X"]], np.float32)
    y = np.array([int(k == t) for _, _, fb, t, _ in R for k in range(len(fb["X"]))])
    print(f"train beats {len(R)}, rows {len(y)}")
    clf = lgb.LGBMClassifier(n_estimators=60, learning_rate=0.12, num_leaves=15, min_child_samples=20, verbose=-1).fit(X, y)
    G = targets(gold, Fg)
    c = collections.Counter()
    for s, b, fb, t, ov in G:
        p = clf.predict_proba(np.array(fb["X"], np.float32))[:, 1]
        k = int(np.argmax(p))
        c["n"] += 1; c["key"] += k == t; c["key_ok"] += ov[k] >= 0.8 * max(ov)
        c["r_model"] += rouge1(fb["sents"][k], b.get("summary", ""))
        c["r_first"] += rouge1(fb["sents"][0], b.get("summary", ""))
        c["r_long"] += rouge1(max(fb["sents"], key=len), b.get("summary", ""))
        c["r_oracle"] += rouge1(fb["sents"][t], b.get("summary", ""))
    n = c["n"]
    print(f"gold beats {n}: key line exact {c['key'] / n:.1%}, near-best {c['key_ok'] / n:.1%}")
    print(f"ROUGE-1 vs Opus summary: model {c['r_model'] / n:.3f}  first-line {c['r_first'] / n:.3f}  longest {c['r_long'] / n:.3f}  oracle {c['r_oracle'] / n:.3f}")
    path = L.ROOT / "public/models/analyzers.json"
    bundle = json.loads(path.read_text())
    bundle["models"]["keyline"] = dump(clf, "binary")
    path.write_text(json.dumps(bundle, separators=(",", ":")))
    (L.ROOT / "src/analyzers/weights.js").write_text("// Generated by tools/analyzers/train.py / train_beats2.py / summary_train.py. Do not edit.\nexport default "
                                                     + json.dumps(bundle, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    main()
