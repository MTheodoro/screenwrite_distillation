"""Dramatic beats (boundaries) + beat mood, trained on Sonnet beat2 labels, tested on Opus majority gold.

  python train_beats2.py            # trains, sweeps decoding threshold / min length on gold, writes bundle entries
Adds models.beat2 (+ meta.beat2) to public/models/analyzers.json and regenerates src/analyzers/weights.js.
"""
import json, subprocess
import lightgbm as lgb
import numpy as np
import beats2 as B
import dataset as DS
import label as L
from train import dump

P = dict(n_estimators=80, learning_rate=0.1, num_leaves=15, max_depth=6, min_child_samples=20, subsample=0.8,
         subsample_freq=1, colsample_bytree=0.8, verbose=-1)


def req(sid, starts=None):
    d = L.load_units(sid)
    return {"scene_id": sid, "source": d["source"], "index": DS.scene_index(sid, d["source"]), "starts": starts or []}


def features(reqs):
    out = subprocess.run(["node", "beats2_features.mjs"], input="".join(json.dumps(r) + "\n" for r in reqs),
                         capture_output=True, text=True, check=True).stdout
    return [json.loads(l) for l in out.splitlines()]


def decode(bundle_path, reqs, thr, min_len):
    out = subprocess.run(["node", "beats2_decode.mjs", bundle_path, str(thr), str(min_len)],
                         input="".join(json.dumps(r) + "\n" for r in reqs), capture_output=True, text=True, check=True).stdout
    return {d["scene_id"]: d["beats"] for d in map(json.loads, out.splitlines())}


def score(pred, gold, tol=1):
    tp = fp = fn = 0; n_p = n_g = 0
    for s, g in gold.items():
        p = pred.get(s, [])
        first = g["starts"][0]
        ps, gs = [x for x in p if x != first], [x for x in g["starts"] if x != first]
        a, b, c = B.f1(ps, gs, tol)
        tp += a; fp += b; fn += c; n_p += len(p); n_g += len(g["starts"])
    return 2 * tp / max(1, 2 * tp + fp + fn), n_p / max(1, len(gold)), n_g / max(1, len(gold))


def main():
    import argparse
    ap = argparse.ArgumentParser(); ap.add_argument("--tags", default="opusT:1,sonnet:0.4,csonnet:0.4")
    a = ap.parse_args()
    train, weight = {}, {}
    for spec in reversed(a.tags.split(",")):  # earlier tags win for scenes labeled twice
        tag, w = spec.split(":")
        for k, v in B.load(tag).items():
            train[k] = v; weight[k] = float(w)
    gold_tags = [t for t in ("opusA", "opusB", "opusC") if B.load(t)]
    gold = B.consensus(gold_tags, need=2)
    train = {k: v for k, v in train.items() if k not in gold}
    print(f"train scenes {len(train)}, gold scenes {len(gold)} (passes {gold_tags})")
    F = features([req(s, [b["start"] for b in v]) for s, v in train.items()])
    X = np.array([x for d in F for x in d["X"]], np.float32); y = np.array([v for d in F for v in d["y"]])
    sw = np.array([weight[d["scene_id"]] for d in F for _ in d["y"]])
    print(f"rows {len(y)}, positive {y.mean():.1%}")
    clf = lgb.LGBMClassifier(**P).fit(X, y, sample_weight=sw)
    path = L.ROOT / "public/models/analyzers.json"
    bundle = json.loads(path.read_text())
    bundle["models"]["beat2"] = dump(clf, "binary")
    tmp = L.DATA / "beat2_tmp.json"
    tmp.write_text(json.dumps(bundle))
    greq = [req(s) for s in gold]
    best = None
    for thr in (0.15, 0.2, 0.25, 0.3, 0.4, "k6", "k7", "k8", "k9", "k10"):
        for ml in (2, 3):
            f, npred, ngold = score(decode(str(tmp), greq, thr, ml), gold)
            print(f"thr {thr} minLen {ml}: F1±1 {f:.3f}  beats/scene {npred:.1f} (gold {ngold:.1f})")
            if not best or f > best[0]:
                best = (f, thr, ml)
    f, thr, ml = best
    f0, _, _ = score(decode(str(tmp), greq, thr, ml), gold, tol=0)
    bundle.setdefault("meta", {})["beat2"] = {"threshold": thr, "minLen": ml, "gold_f1_tol1": f, "gold_f1_exact": f0}
    print(f"best: thr {thr} minLen {ml}  F1±1 {f:.3f}  exact {f0:.3f}")
    path.write_text(json.dumps(bundle, separators=(",", ":")))
    (L.ROOT / "src/analyzers/weights.js").write_text("// Generated by tools/analyzers/train.py / train_beats2.py. Do not edit.\nexport default "
                                                     + json.dumps(bundle, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    main()
