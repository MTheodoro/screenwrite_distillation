"""Unsupervised verb / noun lexicon from the scene corpus -> src/analyzers/verbs.js

Third-person verbs are the words that follow a sentence-leading name or He / She ("Maya grabs", "She smiles");
base-form verbs follow They / Both; nouns follow a determiner ("the chairs", "her coat"). A word is a verb when it is
seen as one clearly more often than as a noun, and vice versa. No labels are used (gold scenes excluded anyway).
  python verb_table.py [--min 3]
"""
import argparse, collections, glob, json, re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCENES = [ROOT / "data" / "analyzers" / "gen" / "scenes", ROOT / "data" / "analyzers" / "pdtrain" / "scenes"]
GOLD = set()
for f in ("gold_all_ids.txt", "gold_ids.txt", "pd_ids.txt"):
    p = ROOT / "data" / "analyzers" / f
    if p.exists():
        GOLD |= set(p.read_text().split())

LEAD = re.compile(r"(?:^|[.!?]\s+)(?:(?:[A-Z][A-Za-z'’.-]+(?:\s+[A-Z][A-Za-z'’.-]+){0,2})|He|She|It)\s+([a-z]+)\b")
# capitalised words that are not names (the subject is then a common noun phrase, "The chairs scrape")
NOT_LEAD = set("The A An His Her Their Its My Your Our Some Two Three Four Five Six Several Every Each This That These Those No Another One Then Now But And Or In On At By For From With Without Behind Beyond Beside Across Through Under Over Outside Inside Somewhere Nobody Someone Everyone Nothing Something Everything Suddenly Slowly Finally Meanwhile Still Yet So As When While After Before Until If Only Even Just Not Later Here There Where What Who How Why".split())
PLURAL_LEAD = re.compile(r"(?:^|[.!?]\s+)(?:They|Both|Several|[A-Z][a-z]+ and [A-Z][a-z]+)\s+([a-z]+)\b")
DET = re.compile(r"\b(?:the|a|an|his|her|their|its|my|your|our|two|three|four|five|these|those|this|that)\s+([a-z]+)\b")
ADV = re.compile(r"ly$")


def action_paragraphs(text):
    out = []
    for para in re.split(r"\n\s*\n", text):
        lines = [l for l in para.split("\n") if l.strip()]
        if not lines:
            continue
        first = lines[0].strip()
        if re.match(r"^(INT|EXT|INT/EXT|I/E)[. ]", first) or first.isupper() or first.endswith("TO:") or first.startswith("("):
            continue
        if len(lines) > 1 and lines[0].strip().isupper():
            continue  # dialogue block
        out.append(" ".join(l.strip() for l in lines))
    return out


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--min", type=int, default=3); a = ap.parse_args()
    v3, vb, noun = collections.Counter(), collections.Counter(), collections.Counter()
    n = 0
    for d in SCENES:
        for f in sorted(glob.glob(str(d / "*.fountain"))):
            if Path(f).stem in GOLD:
                continue
            n += 1
            text = Path(f).read_text()
            # the scene's speakers, as Title-case tokens: only a real character (or He / She) counts as a subject
            cues = set()
            for line in text.split("\n"):
                s = line.strip()
                if s and s.isupper() and not re.match(r"^(INT|EXT|I/E)", s) and not s.endswith(":"):
                    for t in re.sub(r"\(.*?\)", "", s).split():
                        if re.match(r"^[A-Z][A-Z'’.-]+$", t):
                            cues.add(t[0] + t[1:].lower())
            cues |= {"He", "She", "It"}
            for p in action_paragraphs(text):
                for m in LEAD.finditer(p):
                    w = m.group(1)
                    lead = m.group(0).lstrip(".!? ").split()[0]
                    if lead in NOT_LEAD or lead not in cues:
                        continue
                    if not ADV.search(w) and w not in ("and", "or", "who", "then", "is", "was", "has", "had", "does", "did", "the", "a", "an", "of", "in", "at", "on", "to", "with", "but", "as"):
                        v3[w] += 1
                for m in PLURAL_LEAD.finditer(p):
                    w = m.group(1)
                    if not ADV.search(w) and w not in ("and", "or", "are", "were", "have", "had", "do", "did", "both", "all", "the", "a", "an"):
                        vb[w] += 1
                for m in DET.finditer(p):
                    noun[m.group(1)] += 1
    verbs3 = sorted(w for w, c in v3.items() if c >= a.min and c > 1.5 * noun[w] and re.search(r"(?<!s)s$|^(?:is|has|does)$", w))
    verbs_base = sorted(w for w, c in vb.items() if c >= a.min and c > 1.5 * noun[w] and not w.endswith("s"))
    nouns = sorted(w for w, c in noun.items() if c >= a.min and c > 1.5 * (v3[w] + vb[w]))
    both = set(verbs3) & set(nouns)
    out = ROOT / "src" / "analyzers" / "verbs.js"
    out.write_text(
        "// Generated by tools/analyzers/verb_table.py from the scene corpus (no labels). Do not edit.\n"
        "// VERBS3: third-person verbs (\"grabs\"); VERBS: base forms (\"grab\"); NOUNS: words seen after a determiner.\n"
        f"export const VERBS3 = new Set({json.dumps(' '.join(verbs3))}.split(\" \"));\n"
        f"export const VERBS = new Set({json.dumps(' '.join(verbs_base))}.split(\" \"));\n"
        f"export const NOUNS = new Set({json.dumps(' '.join(nouns))}.split(\" \"));\n")
    print(f"{n} scenes: {len(verbs3)} verbs3, {len(verbs_base)} base verbs, {len(nouns)} nouns, {len(both)} in both; {out.stat().st_size // 1024} KB")
    for w in ("adds", "stirs", "pours", "lets", "hits", "swipes", "smiles", "photographs", "chairs", "forks", "string", "steam", "threads", "keys", "lights", "sways", "topple", "clink"):
        print(f"  {w}: v3={v3[w]} vb={vb[w]} noun={noun[w]} -> {'V3' if w in verbs3 else ''}{'B' if w in verbs_base else ''}{'N' if w in nouns else ''}")


if __name__ == "__main__":
    main()
